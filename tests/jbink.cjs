const assert=require('node:assert/strict');
const {guidedResponse:r,matchesIngredient:m}=require(process.env.JBINK_MODULE);
assert.equal(r('pineapple').mood,'surprise');
assert.equal(r('rum and sweet').mood,'surprise');
assert.equal(r('whisky').mood,'bold');
assert.equal(r('dry').mood,'balanced');
assert.equal(r('tart','fruity').mood,'fruity');
assert.equal(r('ingredients','surprise').mood,'surprise');
assert.equal(r('no tequila').mood,undefined);
assert.equal(r('something fruity but not sweet').mood,'fruity');
assert.equal(r('nonalcoholic and tart').mood,undefined);
assert.match(r('nonalcoholic and tart').response,/leave out added syrup/);
assert.notEqual(r('how do I measure').response,r('how do I stir').response);
assert.equal(m('pineapple syrup','pineapple'),false);
assert.equal(m('honey whiskey','honey'),false);
assert.equal(m('non-alcoholic rum','rum'),false);
assert.equal(m('fresh lime juice','lime'),true);
